def traced(default_policy: Any) -> tuple[Gate, InMemorySpanExporter]:
    exporter = InMemorySpanExporter()
    return create_gate(ASSET, MemoryStore(), None, default_policy, span_exporter=exporter), exporter


def run_turn(gate: Gate) -> str:
    with gate.trace.turn("s-1", "QID 28263425117?", user_id="u-9") as root:
        with gate.trace.model("gemini-2.5-flash", "hello") as span:
            span.set({"llm.token_count.prompt": 12, "llm.token_count.completion": 5, "output.value": "call lookup"})
        with gate.trace.tool("lookup_sme", {"name": "النور"}) as span:
            found = {"qid": "28263425117"}
            span.set({"output.value": json.dumps(found, separators=(",", ":"))})
        root.set({"output.value": f"found {found['qid']}"})
    return "done"


def test_trace_emits_root_with_model_and_tool_children() -> None:
    gate, exporter = traced({"version": 0, "telemetry": {"enabled": True}})
    assert run_turn(gate) == "done"
    gate.trace.flush()
    spans = {s.name: s for s in exporter.get_finished_spans()}
    assert sorted(spans) == ["agent.turn", "llm.generate", "tool.lookup_sme"]
    root, llm, tool = spans["agent.turn"], spans["llm.generate"], spans["tool.lookup_sme"]
    assert root.parent is None
    for child in (llm, tool):
        assert child.context.trace_id == root.context.trace_id
        assert child.parent is not None
        assert child.parent.span_id == root.context.span_id
    for span in spans.values():
        assert span.attributes is not None
        assert span.attributes["session.id"] == "s-1"
        assert span.attributes["user.id"] == "u-9"
    assert root.attributes is not None and llm.attributes is not None and tool.attributes is not None
    assert root.attributes["openinference.span.kind"] == "AGENT"
    assert root.attributes["input.value"] == "QID 28263425117?"
    assert root.attributes["output.value"] == "found 28263425117"
    assert llm.attributes["openinference.span.kind"] == "LLM"
    assert llm.attributes["llm.model_name"] == "gemini-2.5-flash"
    assert llm.attributes["llm.token_count.prompt"] == 12
    assert tool.attributes["tool.name"] == "lookup_sme"
    assert tool.attributes["tool.parameters"] == '{"name":"النور"}'
    assert tool.attributes["output.value"] == '{"qid":"28263425117"}'


def test_trace_masks_when_policy_masks_logs() -> None:
    gate, exporter = traced({"version": 0, "telemetry": {"enabled": True}, "logging": {"maskPersonalData": True}})
    run_turn(gate)
