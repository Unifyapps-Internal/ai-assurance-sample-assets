STRICT: dict[str, Any] = VECTORS["signature"]["policy"]
ASSET = "e2-onboarding-helper"
SECRET = "unit-test-secret"
T0 = datetime(2026, 11, 13, 10, 0, tzinfo=UTC).timestamp() * 1000
LABEL = "Generated by AI. Review before use."


class Harness:
    def __init__(self, default_policy: Any = None, store: Any = None, secret: str | None = SECRET) -> None:
        self.now = T0
        self.lines: list[str] = []
        self.store = store if store is not None else MemoryStore()
        self.gate: Gate = create_gate(
            ASSET,
            self.store,
            secret,
            default_policy if default_policy is not None else {"version": 0},
            now=lambda: self.now,
            sink=self.lines.append,
        )

    def signed(self, policy: Any, ts: Any = None, secret: str = SECRET) -> dict[str, Any]:
        stamp = int(self.now) if ts is None else ts
        return {"policy": policy, "ts": stamp, "signature": sign(secret, stamp, policy)}

    def post(self, path: str, body: Any) -> tuple[int, dict[str, Any]]:
        response = self.gate.handle("POST", path, body)
        assert response is not None
        return response

    def push(self, policy: Any) -> tuple[int, dict[str, Any]]:
        return self.post("/_assurance/policy", self.signed(policy))


def versioned(version: int, **extra: Any) -> dict[str, Any]:
    return {**STRICT, "version": version, **extra}


class FlakyStore(MemoryStore):
    def __init__(self) -> None:
        super().__init__()
        self.fail_reads = False
        self.fail_writes = False
        self.empty = False

    def read(self) -> dict[str, Any] | None:
        if self.fail_reads:
            raise OSError("store offline")
        return None if self.empty else super().read()

    def write(self, state: dict[str, Any]) -> None:
        if self.fail_writes:
            raise OSError("store read-only")
        super().write(state)


