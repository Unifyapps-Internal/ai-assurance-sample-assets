def test_signature_matches_the_shared_vector() -> None:
    v = VECTORS["signature"]
    assert sign(v["secret"], v["ts"], v["policy"]) == v["expected"]
    assert verify_signature(v["secret"], v["ts"], v["policy"], v["expected"])
    assert verify_signature(v["secret"], v["ts"], v["policy"], v["expected"].upper())


def test_signature_rejects_changes() -> None:
    v = VECTORS["signature"]
    assert not verify_signature(v["secret"], v["ts"], {**v["policy"], "version": 8}, v["expected"])
    assert not verify_signature(v["secret"], v["ts"] + 1, v["policy"], v["expected"])
    assert not verify_signature("other", v["ts"], v["policy"], v["expected"])
    assert not verify_signature(v["secret"], v["ts"], v["policy"], None)


def test_parse_timestamp_forms() -> None:
    assert parse_timestamp(1794560400000) == 1794560400000
    assert parse_timestamp(1794560400) == 1794560400000
    assert parse_timestamp("1794560400000") == 1794560400000
    assert parse_timestamp("2026-11-13T10:00:00Z") == T0
    assert parse_timestamp("2026-11-13T10:00:00.000Z") == T0
    assert parse_timestamp("soon") is None
    assert parse_timestamp(None) is None
    assert parse_timestamp(True) is None


def test_freshness_window_is_five_minutes() -> None:
    assert is_fresh(T0 - 299_000, T0)
    assert not is_fresh(T0 - 301_000, T0)
    assert not is_fresh(T0 + 301_000, T0)


